def serialized_factor_catalog() -> list[dict[str, object]]:
    result: list[dict[str, object]] = []
    for item in MATRIX_FACTORS:
        payload = asdict(item)
        payload["status"] = item.status.value
        payload["variables"] = list(item.variables)
        result.append(payload)
    return result
